import {existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {ZIP_RECIPE, byPath, makeZip, readZip, sha256Hex} from './zip.mjs';

// Deterministic SDK distribution artifact for the owner CI release lane.
//
//   node tools/owner-ci/release.mjs inventory [--root <dir>]
//   node tools/owner-ci/release.mjs assemble --root <dir> --out-dir <dir-outside-repo>
//        [--run-url <url>] [--commit <40-hex>] [--command <cmd>]...
//   node tools/owner-ci/release.mjs verify --artifact <zip> --manifest <json> --receipt <json>
//        [--root <dir>] [--expect-head <40-hex>] [--distribution-dir <dir>]
//
// The whitelist (tools/owner-ci/dist-files.json) lives next to this tool, so the
// recipe is the tooling version's, while every packaged byte is re-read from the
// tested root and compared with the git blob at the released commit. A dirty or
// drifted worktree therefore cannot ship: content that is not the commit's
// content is a hard failure.
//
// Layout: the zip root is the consumer distribution directory
// (web/runtime-sdk/dnd5e-runtime), so its files drop in by name. The consumer's
// dnd5e-runtime.manifest.json pin is generated by the consumer's own sync tool;
// this tool binds it (commit/hashes/identity) instead of fabricating it.
//
// manifest/receipt are written only after the zip round-trips through readZip and
// a real unpack into a temporary directory; receipt.runUrl is null outside CI.
const TOOL = 'tools/owner-ci/release.mjs';
const TOOL_DIR = path.dirname(fileURLToPath(import.meta.url));
const DIST_FILES_PATH = path.join(TOOL_DIR, 'dist-files.json');
const MANIFEST_SCHEMA = 'arcane-dnd5e-runtime-sdk-artifact/1';
const RECEIPT_SCHEMA = 'arcane-dnd5e-runtime-sdk-artifact-receipt/1';
const DIST_FILES_SCHEMA = 'arcane-dnd5e-runtime-sdk-dist-files/1';
const HASH_NAMESPACE = 'arcane-dnd5e-runtime-sdk-set-hash/1';
const ZIP_FILE = 'dnd5e-runtime-sdk.zip';
const MANIFEST_FILE = 'dnd5e-runtime-sdk-manifest.json';
const RECEIPT_FILE = 'dnd5e-runtime-sdk-receipt.json';
const RUNTIME_PACKAGE = 'packages/dnd5e-runtime';
const DIST_DIR = `${RUNTIME_PACKAGE}/dist`;
const SOURCE_PATH = `${RUNTIME_PACKAGE}/src/automation.js`;
const BASELINE_PATH = `${RUNTIME_PACKAGE}/src/source-baseline.json`;
const PACKAGE_JSON_PATH = `${RUNTIME_PACKAGE}/package.json`;
const CONTRACT = Object.freeze({
  package: '@arcanedesk/dnd5e-runtime',
  schemaVersion: 1,
  runtimeKind: 'full',
  factoryName: 'initializeDnd5eRuntime',
  moduleId: 'arcane-dnd5e-2014-automation',
  contentPolicy: 'runtime-only',
  sourcePath: 'src/automation.js',
  artifactPath: 'dist/dnd5e-runtime.mjs',
});
const ROLES = ['artifact', 'license', 'notice', 'sdk-manifest'];

const usage = (message) => {
  if (message) console.error(`${message}\n`);
  console.error(`usage:
  node ${TOOL} inventory [--root <dir>]
  node ${TOOL} assemble --root <dir> --out-dir <dir> [--run-url <url>] [--commit <40-hex>] [--command <cmd>]...
  node ${TOOL} verify --artifact <zip> --manifest <json> --receipt <json>
      [--root <dir>] [--expect-head <40-hex>] [--distribution-dir <dir>]`);
  process.exit(1);
};

const parseArgs = (argv) => {
  const args = {commands: []};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    const eq = arg.indexOf('=');
    const key = arg.startsWith('--') && eq > 0 ? arg.slice(0, eq) : arg;
    const inline = arg.startsWith('--') && eq > 0 ? arg.slice(eq + 1) : undefined;
    const value = () => {
      if (inline !== undefined) return inline;
      index += 1;
      if (index >= argv.length) usage(`${key} 缺少参数`);
      return argv[index];
    };
    switch (key) {
      case 'inventory':
      case 'assemble':
      case 'verify':
        if (args.command) usage(`重复的子命令 ${key}`);
        args.command = key;
        break;
      case '--root': args.root = value(); break;
      case '--out-dir': args.outDir = value(); break;
      case '--run-url': {
        const raw = value();
        args.runUrl = raw === 'null' ? null : raw;
        break;
      }
      case '--commit': args.commit = value(); break;
      case '--command': args.commands.push(value()); break;
      case '--artifact': args.artifact = value(); break;
      case '--manifest': args.manifest = value(); break;
      case '--receipt': args.receipt = value(); break;
      case '--expect-head': args.expectHead = value(); break;
      case '--distribution-dir': args.distributionDir = value(); break;
      default: usage(`未知参数 ${arg}`);
    }
  }
  return args;
};

const isSha256 = (value) => typeof value === 'string' && /^[0-9a-f]{64}$/.test(value);
const isFullCommit = (value) => typeof value === 'string' && /^[0-9a-f]{40}$/.test(value);
const sha256 = sha256Hex;
const canonicalSetHash = (files) => sha256Hex(
  [...files].sort(byPath).map(file => `${file.path}\n${file.size}\n${file.sha256}\n`).join(''),
);

const fail = (problems, headline = 'SDK 出件校验失败') => {
  console.error(`${headline}（${problems.length} 条）：`);
  problems.slice(0, 20).forEach(problem => console.error(`  - ${problem}`));
  process.exit(1);
};

const readJson = (file, label, problems) => {
  try {
    const bytes = readFileSync(file);
    return {bytes, json: JSON.parse(bytes.toString('utf8'))};
  } catch (error) {
    problems.push(`${label} 无法读取或不是合法 JSON: ${file}: ${error.message}`);
    return {bytes: null, json: null};
  }
};

const readText = (file) => readFileSync(file, 'utf8');

const git = (root, args, encoding = 'utf8') => spawnSync('git', ['-C', root, ...args], {
  encoding,
  maxBuffer: 256 * 1024 * 1024,
});

const gitText = (root, args) => {
  const result = git(root, args);
  if (result.status !== 0) {
    throw new Error(`git ${args.join(' ')} 失败: ${(result.stderr || '').trim()}`);
  }
  return result.stdout.trim();
};

const gitBlob = (root, commit, relative) => {
  const result = git(root, ['cat-file', 'blob', `${commit}:${relative}`], null);
  return result.status === 0 ? result.stdout : null;
};

const relativeInside = (candidate, parent) => {
  const relative = path.relative(parent, candidate);
  return relative === '' || (!relative.startsWith('..') && !path.isAbsolute(relative));
};

const loadWhitelist = (problems) => {
  const {json: whitelist} = readJson(DIST_FILES_PATH, 'tools/owner-ci/dist-files.json', problems);
  if (!whitelist) return null;
  if (whitelist.schema !== DIST_FILES_SCHEMA) {
    problems.push(`dist-files.schema ${whitelist.schema} != ${DIST_FILES_SCHEMA}`);
  }
  if (typeof whitelist.distributionRoot !== 'string' || !whitelist.distributionRoot) {
    problems.push('dist-files.distributionRoot 缺失');
  }
  const members = Array.isArray(whitelist.members) ? whitelist.members : [];
  const paths = members.map(member => member?.path);
  const sources = members.map(member => member?.source);
  if (new Set(paths).size !== paths.length) problems.push('dist-files.members 存在重复的发行名');
  if (new Set(sources).size !== sources.length) problems.push('dist-files.members 存在重复的源路径');
  for (const member of members) {
    if (typeof member?.path !== 'string' || !member.path || member.path.includes('/')) {
      problems.push(`dist-files.members 的发行名必须是 zip 根下的纯文件名: ${JSON.stringify(member?.path)}`);
    }
    if (typeof member?.source !== 'string' || !member.source.startsWith(`${RUNTIME_PACKAGE}/`)) {
      problems.push(`dist-files.members 的源路径必须落在 ${RUNTIME_PACKAGE}/ 内: ${JSON.stringify(member?.source)}`);
    }
    if (!ROLES.includes(member?.role)) problems.push(`dist-files.members 的 role 非法: ${member?.role}`);
  }
  for (const role of ROLES) {
    if (!members.some(member => member?.role === role)) problems.push(`dist-files.members 缺少 role=${role}`);
  }
  const generated = whitelist.consumerGenerated;
  if (!generated || typeof generated.path !== 'string' || !generated.path) {
    problems.push('dist-files.consumerGenerated 缺失');
  } else if (paths.includes(generated.path)) {
    problems.push(`consumerGenerated 的 ${generated.path} 不得同时是 zip 成员（由消费方生成）`);
  }
  return whitelist;
};

// Reads the whitelisted files from the tested root, proves each byte equals the
// git blob at <commit>, and cross-checks the SDK manifest identity/hashes.
const collectMembers = ({root, commit, whitelist, problems}) => {
  const entries = [];
  const files = [];
  for (const member of [...whitelist.members].sort(byPath)) {
    const absolute = path.join(root, member.source);
    let bytes;
    try {
      bytes = readFileSync(absolute);
    } catch (error) {
      problems.push(`缺少分发面文件 ${member.source}: ${error.message}`);
      continue;
    }
    const blob = gitBlob(root, commit, member.source);
    if (!blob) {
      problems.push(`${member.source} 在 commit ${commit} 中不存在（未跟踪或路径写错）`);
    } else if (!blob.equals(bytes)) {
      problems.push(`${member.source} 的工作树字节与 commit ${commit} 的 blob 不一致（先提交或还原再出件）`);
    }
    entries.push({path: member.path, bytes});
    files.push({path: member.path, source: member.source, role: member.role, size: bytes.length, sha256: sha256(bytes)});
  }
  if (problems.length) return {entries, files, identity: null};

  const byRole = new Map(files.map(file => [file.role, file]));
  const artifact = byRole.get('artifact');
  const sdkManifestFile = byRole.get('sdk-manifest');
  const sdkManifestBytes = entries.find(entry => entry.path === sdkManifestFile.path).bytes;
  let sdkManifest;
  try {
    sdkManifest = JSON.parse(sdkManifestBytes.toString('utf8'));
  } catch (error) {
    problems.push(`sdk-manifest 不是合法 JSON: ${error.message}`);
    return {entries, files, identity: null};
  }
  const packageJson = JSON.parse(readText(path.join(root, PACKAGE_JSON_PATH)));
  const baselineBytes = readFileSync(path.join(root, BASELINE_PATH));
  const baseline = JSON.parse(baselineBytes.toString('utf8'));
  const sourceBytes = readFileSync(path.join(root, SOURCE_PATH));
  const sourceHash = sha256(sourceBytes);

  if (sdkManifest.name !== CONTRACT.package || sdkManifest.name !== packageJson.name) {
    problems.push(`sdk-manifest.name ${sdkManifest.name} 与契约/package.json 不一致`);
  }
  if (sdkManifest.version !== packageJson.version) {
    problems.push(`sdk-manifest.version ${sdkManifest.version} 与 package.json ${packageJson.version} 不一致`);
  }
  for (const field of ['schemaVersion', 'runtimeKind', 'factoryName', 'moduleId', 'contentPolicy']) {
    if (sdkManifest[field] !== CONTRACT[field]) {
      problems.push(`sdk-manifest.${field} ${JSON.stringify(sdkManifest[field])} != ${JSON.stringify(CONTRACT[field])}`);
    }
  }
  if (sdkManifest.artifact?.path !== CONTRACT.artifactPath) {
    problems.push(`sdk-manifest.artifact.path ${sdkManifest.artifact?.path} != ${CONTRACT.artifactPath}`);
  }
  if (sdkManifest.artifact?.sha256 !== artifact.sha256 || sdkManifest.buildHash !== artifact.sha256) {
    problems.push(`sdk-manifest 声明的 artifact hash 与 ${artifact.source} 实际字节不符`);
  }
  if (sdkManifest.artifact?.bytes !== artifact.size) {
    problems.push(`sdk-manifest.artifact.bytes ${sdkManifest.artifact?.bytes} != 实际 ${artifact.size}`);
  }
  if (sdkManifest.source?.path !== CONTRACT.sourcePath) {
    problems.push(`sdk-manifest.source.path ${sdkManifest.source?.path} != ${CONTRACT.sourcePath}`);
  }
  if (sdkManifest.source?.sha256 !== sourceHash || sdkManifest.sourceHash !== sourceHash) {
    problems.push(`sdk-manifest 声明的 source hash 与 ${SOURCE_PATH} 实际字节不符`);
  }
  if (sdkManifest.source?.bytes !== sourceBytes.length) {
    problems.push(`sdk-manifest.source.bytes ${sdkManifest.source?.bytes} != 实际 ${sourceBytes.length}`);
  }
  if (baseline.sha256 !== sourceHash) {
    problems.push(`${BASELINE_PATH} 的审查哈希 ${baseline.sha256} 与 ${SOURCE_PATH} 实际 ${sourceHash} 不符`);
  }
  if (baseline.review?.refreshPolicy !== 'manual-only') {
    problems.push(`${BASELINE_PATH} 的 review.refreshPolicy 必须是 manual-only`);
  }
  if (sdkManifest.baseline?.sha256 !== sha256(baselineBytes)) {
    problems.push('sdk-manifest.baseline.sha256 与源树 source-baseline.json 字节不符');
  }
  if (sdkManifest.provenance?.testedRuntimeSha256 !== sourceHash) {
    problems.push('sdk-manifest.provenance.testedRuntimeSha256 与源哈希不符');
  }

  const license = entries.find(entry => entry.path === byRole.get('license').path).bytes.toString('utf8');
  if (!license.includes('Apache License') || !license.includes('Version 2.0') || license.length < 1000) {
    problems.push('LICENSE 成员不是完整的 Apache-2.0 文本');
  }
  const notice = entries.find(entry => entry.path === byRole.get('notice').path).bytes.toString('utf8');
  if (!notice.includes('ArcaneDesk')) problems.push('NOTICE 成员缺少 ArcaneDesk 归属声明');

  const distFiles = readdirSync(path.join(root, DIST_DIR)).sort();
  const declared = files.filter(file => file.source.startsWith(`${DIST_DIR}/`))
    .map(file => path.posix.basename(file.source)).sort();
  if (distFiles.length !== declared.length || distFiles.some((name, index) => name !== declared[index])) {
    problems.push(`${DIST_DIR}/ 的目录内容 ${JSON.stringify(distFiles)} 与白名单 ${JSON.stringify(declared)} 不符`);
  }

  const identity = {
    package: sdkManifest.name,
    version: sdkManifest.version,
    moduleId: sdkManifest.moduleId,
    schemaVersion: sdkManifest.schemaVersion,
    runtimeKind: sdkManifest.runtimeKind,
    factoryName: sdkManifest.factoryName,
    contentPolicy: sdkManifest.contentPolicy,
    source: {path: SOURCE_PATH, bytes: sourceBytes.length, sha256: sourceHash},
    artifact: {
      sourcePath: artifact.source,
      distributionPath: artifact.path,
      bytes: artifact.size,
      sha256: artifact.sha256,
    },
    sdkManifest: {
      sourcePath: sdkManifestFile.source,
      distributionPath: sdkManifestFile.path,
      bytes: sdkManifestFile.size,
      sha256: sdkManifestFile.sha256,
    },
  };
  return {entries, files, identity};
};

// Writes the zip members out to a throwaway directory and reads them back, so the
// archive is proven extractable and byte-identical to the tested source tree.
const unpackAndCompare = ({entries, files, root, problems}) => {
  const dir = mkdtempSync(path.join(tmpdir(), 'dnd5e-sdk-unpack-'));
  try {
    for (const entry of entries) writeFileSync(path.join(dir, entry.path), entry.bytes);
    const unpacked = readdirSync(dir).sort();
    const expected = entries.map(entry => entry.path).sort();
    if (unpacked.length !== expected.length || unpacked.some((name, index) => name !== expected[index])) {
      problems.push(`解包文件集 ${JSON.stringify(unpacked)} 与 zip 成员 ${JSON.stringify(expected)} 不符`);
    }
    for (const entry of entries) {
      const back = readFileSync(path.join(dir, entry.path));
      if (sha256(back) !== entry.sha256) problems.push(`解包后的 ${entry.path} 字节与 zip 内成员不一致`);
      if (!root) continue;
      const file = files.find(candidate => candidate.path === entry.path);
      const sourceBytes = readFileSync(path.join(root, file.source));
      if (!sourceBytes.equals(back)) problems.push(`解包后的 ${entry.path} 与源树 ${file.source} 不逐字节一致`);
    }
  } finally {
    rmSync(dir, {recursive: true, force: true});
  }
};

const checkSdkManifestInZip = ({entries, files, problems}) => {
  const sdkFile = files.find(file => file.role === 'sdk-manifest');
  const artifactFile = files.find(file => file.role === 'artifact');
  const entry = entries.find(candidate => candidate.path === sdkFile.path);
  const artifactEntry = entries.find(candidate => candidate.path === artifactFile.path);
  if (!entry || !artifactEntry) {
    problems.push('zip 内缺少 artifact / sdk-manifest 成员');
    return;
  }
  let manifest;
  try {
    manifest = JSON.parse(entry.bytes.toString('utf8'));
  } catch (error) {
    problems.push(`zip 内 sdk-manifest 不是合法 JSON: ${error.message}`);
    return;
  }
  if (manifest.buildHash !== artifactEntry.sha256 || manifest.artifact?.sha256 !== artifactEntry.sha256) {
    problems.push('zip 内 sdk-manifest 的 artifact hash 与 zip 内 artifact 成员不符');
  }
  if (manifest.artifact?.path !== CONTRACT.artifactPath) problems.push('zip 内 sdk-manifest.artifact.path 不符合契约');
  if (manifest.contentPolicy !== CONTRACT.contentPolicy) problems.push('zip 内 sdk-manifest.contentPolicy 不符合契约');
};

const checkDistributionDir = ({dir, entries, files, unit, manifest, whitelist, problems, notes}) => {
  for (const entry of entries) {
    const absolute = path.join(dir, entry.path);
    if (!existsSync(absolute)) {
      problems.push(`消费方分发目录缺少 ${entry.path}`);
      continue;
    }
    if (!readFileSync(absolute).equals(entry.bytes)) {
      problems.push(`消费方分发目录的 ${entry.path} 与 zip 成员不逐字节一致`);
    }
  }
  const pinPath = path.join(dir, whitelist.consumerGenerated.path);
  if (!existsSync(pinPath)) {
    notes.push(`消费方分发目录没有 ${whitelist.consumerGenerated.path}（由消费方 sync 工具生成）`);
    return;
  }
  const {json: pin} = readJson(pinPath, '消费方 distribution pin', problems);
  if (!pin) return;
  const artifactFile = files.find(file => file.role === 'artifact');
  if (pin.artifact?.sha256 !== artifactFile.sha256 || pin.buildHash !== artifactFile.sha256) {
    problems.push(`消费方 pin 的 buildHash/artifact.sha256 与本次出件 artifact 字节不符`);
  }
  if (pin.sourceHash !== unit.source?.sha256) problems.push('消费方 pin 的 sourceHash 与本次出件源哈希不符');
  const sdkFile = files.find(file => file.role === 'sdk-manifest');
  if (pin.sdkManifest?.sha256 !== sdkFile.sha256) problems.push('消费方 pin 的 sdkManifest.sha256 与本次出件 manifest 字节不符');
  for (const field of ['package', 'version', 'schemaVersion', 'runtimeKind', 'factoryName', 'moduleId', 'contentPolicy']) {
    if (pin[field] !== unit[field]) problems.push(`消费方 pin 的 ${field} 与本次出件身份不符`);
  }
  if (!isFullCommit(pin.commit)) problems.push('消费方 pin 的 commit 不是完整 40 位');
  if (pin.commit === manifest.commit) {
    notes.push(`消费方 pin 已绑定本次 commit ${manifest.commit}`);
  } else {
    notes.push(`消费方 pin 仍绑定 commit ${pin.commit}（本次出件 ${manifest.commit}；字节绑定一致，采纳侧需重新生成 pin）`);
  }
};

const inspect = ({artifact, manifest: manifestPath, receipt: receiptPath, root, expectHead, distributionDir, whitelist}) => {
  const problems = [];
  const notes = [];
  const zipBytes = readFileSync(artifact);
  const parsedZip = readZip(zipBytes);
  problems.push(...parsedZip.problems);
  const entries = parsedZip.entries;

  const manifestFile = readJson(manifestPath, 'artifact manifest', problems);
  const receiptFile = readJson(receiptPath, 'artifact receipt', problems);
  if (!manifestFile.json || !receiptFile.json) return {problems, notes, entries, manifest: null, receipt: null};
  const {json: manifest} = manifestFile;
  const {json: receipt} = receiptFile;

  if (manifest.schema !== MANIFEST_SCHEMA) problems.push(`manifest.schema ${manifest.schema} != ${MANIFEST_SCHEMA}`);
  if (manifest.hashNamespace !== HASH_NAMESPACE) problems.push(`manifest.hashNamespace ${manifest.hashNamespace} != ${HASH_NAMESPACE}`);
  if (manifest.generatedBy !== TOOL) problems.push(`manifest.generatedBy ${manifest.generatedBy} != ${TOOL}`);
  if (!isFullCommit(manifest.commit)) problems.push(`manifest.commit 不是完整 40 位: ${JSON.stringify(manifest.commit)}`);
  if (manifest.distribution?.root !== whitelist.distributionRoot) problems.push('manifest.distribution.root 与白名单不符');

  const artifactMeta = manifest.artifact ?? {};
  if (artifactMeta.path !== ZIP_FILE) problems.push(`manifest.artifact.path ${artifactMeta.path} != ${ZIP_FILE}`);
  if (artifactMeta.zipRecipe !== ZIP_RECIPE) problems.push('manifest.artifact.zipRecipe 与 recipe 常量不符');
  if (artifactMeta.layout !== 'distribution-root') problems.push('manifest.artifact.layout 必须是 distribution-root');
  if (artifactMeta.sha256 !== sha256(zipBytes)) problems.push('manifest.artifact.sha256 与 zip 实际字节不符');
  if (artifactMeta.size !== zipBytes.length) problems.push('manifest.artifact.size 与 zip 实际大小不符');

  const files = Array.isArray(manifest.files) ? manifest.files : [];
  if (files.length === 0) problems.push('manifest.files 为空');
  if (artifactMeta.fileCount !== files.length) problems.push('manifest.artifact.fileCount 与 manifest.files 数量不符');
  if (files.length !== entries.length) problems.push(`zip 成员数 ${entries.length} != manifest.files ${files.length}`);
  for (let index = 0; index < files.length; index += 1) {
    const file = files[index] ?? {};
    if (typeof file.path !== 'string' || !file.path) problems.push(`manifest.files[${index}] 缺少 path`);
    if (!Number.isInteger(file.size) || file.size < 0) problems.push(`manifest.files[${index}] size 非法`);
    if (!isSha256(file.sha256)) problems.push(`manifest.files[${index}] sha256 非法`);
    if (!ROLES.includes(file.role)) problems.push(`manifest.files[${index}] role 非法: ${file.role}`);
    if (typeof file.source !== 'string' || !file.source) problems.push(`manifest.files[${index}] 缺少 source`);
    if (index > 0 && byPath(files[index - 1], file) >= 0) problems.push(`manifest.files 未按 path 严格升序: ${file.path}`);
    const entry = entries[index];
    if (!entry) continue;
    if (entry.path !== file.path || entry.size !== file.size || entry.sha256 !== file.sha256) {
      problems.push(`manifest.files[${index}] 与 zip 第 ${index} 个成员不一致: ${file.path} / ${entry.path}`);
    }
  }
  if (manifest.setHash !== canonicalSetHash(files)) problems.push('manifest.setHash 与 manifest.files 重算结果不符');

  const unit = manifest.unit ?? {};
  const artifactFile = files.find(file => file.role === 'artifact');
  if (!artifactFile) problems.push('manifest.files 缺少 role=artifact');
  else if (unit.artifact?.sha256 !== artifactFile.sha256 || unit.artifact?.bytes !== artifactFile.size) {
    problems.push('manifest.unit.artifact 与 artifact 成员不符');
  }
  if (unit.package !== CONTRACT.package) problems.push(`manifest.unit.package ${unit.package} != ${CONTRACT.package}`);
  for (const field of ['schemaVersion', 'runtimeKind', 'factoryName', 'moduleId', 'contentPolicy']) {
    if (unit[field] !== CONTRACT[field]) problems.push(`manifest.unit.${field} 不符合契约`);
  }
  if (!isSha256(unit.source?.sha256)) problems.push('manifest.unit.source.sha256 非法');

  if (receipt.schema !== RECEIPT_SCHEMA) problems.push(`receipt.schema ${receipt.schema} != ${RECEIPT_SCHEMA}`);
  if (receipt.kind !== 'sdk-artifact') problems.push(`receipt.kind ${receipt.kind} != sdk-artifact`);
  if (receipt.result !== 'passed') problems.push(`receipt.result=${receipt.result}，非绿结果不得出件`);
  if (receipt.runUrl !== null && (typeof receipt.runUrl !== 'string' || receipt.runUrl.length === 0)) {
    problems.push('receipt.runUrl 必须是 null 或非空字符串');
  }
  if (receipt.generatedBy !== TOOL) problems.push(`receipt.generatedBy ${receipt.generatedBy} != ${TOOL}`);
  if (!isFullCommit(receipt.commit) || receipt.commit !== manifest.commit) problems.push('receipt.commit 与 manifest.commit 不一致或不是完整 40 位');
  if (!Array.isArray(receipt.commands) || receipt.commands.length === 0) problems.push('receipt.commands 为空');
  if (receipt.manifest !== MANIFEST_FILE) problems.push(`receipt.manifest ${receipt.manifest} != ${MANIFEST_FILE}`);
  if (receipt.manifestSha256 !== sha256(manifestFile.bytes)) problems.push('receipt.manifestSha256 与 manifest 实际字节不符');
  if (receipt.artifact?.path !== ZIP_FILE) problems.push('receipt.artifact.path 与 zip 名不符');
  if (receipt.artifact?.sha256 !== artifactMeta.sha256) problems.push('receipt.artifact.sha256 与 manifest 不符');
  if (receipt.artifact?.size !== zipBytes.length) problems.push('receipt.artifact.size 与 zip 实际大小不符');
  if (receipt.setHash !== manifest.setHash) problems.push('receipt.setHash != manifest.setHash');
  if (receipt.unit?.buildHash !== artifactFile?.sha256) problems.push('receipt.unit.buildHash 与 artifact 成员不符');
  if (receipt.unit?.sourceHash !== unit.source?.sha256) problems.push('receipt.unit.sourceHash 与 manifest.unit.source 不符');

  if (problems.length === 0) checkSdkManifestInZip({entries, files, problems});

  if (root) {
    let head = null;
    try {
      head = gitText(root, ['rev-parse', 'HEAD']);
    } catch (error) {
      problems.push(`--root 不是可用的 git checkout: ${error.message}`);
    }
    if (head && head !== manifest.commit) problems.push(`--root HEAD ${head} != manifest.commit ${manifest.commit}`);
    if (head && expectHead && head !== expectHead) problems.push(`--root HEAD ${head} != --expect-head ${expectHead}`);
    for (const file of files) {
      let bytes;
      try {
        bytes = readFileSync(path.join(root, file.source));
      } catch (error) {
        problems.push(`源树缺少 ${file.source}: ${error.message}`);
        continue;
      }
      if (sha256(bytes) !== file.sha256) problems.push(`源树 ${file.source} 的 sha256 与 manifest 不符`);
      const blob = gitBlob(root, manifest.commit, file.source);
      if (!blob) problems.push(`${file.source} 在 commit ${manifest.commit} 中不存在`);
      else if (sha256(blob) !== file.sha256) problems.push(`commit ${manifest.commit} 的 ${file.source} blob 与 manifest 不符`);
    }
  }

  // The zip must unpack into exactly its member set and match both the tested
  // source tree and (when supplied) the consumer distribution directory.
  if (problems.length === 0) unpackAndCompare({entries, files, root: root ?? null, problems});

  if (distributionDir) checkDistributionDir({dir: distributionDir, entries, files, unit, manifest, whitelist, problems, notes});
  return {problems, notes, entries, manifest, receipt};
};

const assemble = (args) => {
  const problems = [];
  const root = path.resolve(args.root ?? process.cwd());
  const outDir = path.resolve(args.outDir ?? '');
  if (!args.outDir) usage('assemble 需要 --out-dir');
  if (relativeInside(outDir, root)) {
    fail([`--out-dir 必须位于仓外：仓内的 .zip 会被 pack:check/content audit 判红（收到 ${outDir}）`]);
  }
  let commit;
  try {
    commit = gitText(root, ['rev-parse', 'HEAD']);
  } catch (error) {
    fail([`--root 不是可用的 git checkout: ${error.message}`]);
  }
  if (!isFullCommit(commit)) fail([`HEAD 不是完整 40 位 commit: ${commit}`]);
  if (args.commit && args.commit !== commit) {
    fail([`--commit ${args.commit} 与 --root HEAD ${commit} 不一致`]);
  }
  const whitelist = loadWhitelist(problems);
  if (problems.length) fail(problems, '出件白名单/参数非法');

  const {entries, files, identity} = collectMembers({root, commit, whitelist, problems});
  if (problems.length) fail(problems, '分发面与 commit 字节/身份校验失败');

  const zipBytes = makeZip(entries);
  if (!makeZip(entries).equals(zipBytes)) fail(['两次构建得到的 zip 字节不一致（recipe 非确定性）']);
  const setHash = canonicalSetHash(files);
  const artifact = {
    path: ZIP_FILE,
    sha256: sha256(zipBytes),
    size: zipBytes.length,
    fileCount: entries.length,
    contentBytes: files.reduce((sum, file) => sum + file.size, 0),
    zipRecipe: ZIP_RECIPE,
    layout: 'distribution-root',
  };
  const manifest = {
    schema: MANIFEST_SCHEMA,
    commit,
    unit: identity,
    distribution: {
      root: whitelist.distributionRoot,
      members: files.map(file => file.path),
      consumerGenerated: whitelist.consumerGenerated,
    },
    artifact,
    files,
    hashNamespace: HASH_NAMESPACE,
    setHash,
    generatedBy: TOOL,
  };
  mkdirSync(outDir, {recursive: true});
  writeFileSync(path.join(outDir, ZIP_FILE), zipBytes);
  const manifestBytes = Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
  writeFileSync(path.join(outDir, MANIFEST_FILE), manifestBytes);
  const commands = [
    ...args.commands,
    'node tools/owner-ci/release.mjs assemble',
    `node tools/owner-ci/release.mjs verify --artifact ${ZIP_FILE} --manifest ${MANIFEST_FILE} --receipt ${RECEIPT_FILE}`,
  ];
  const receipt = {
    schema: RECEIPT_SCHEMA,
    kind: 'sdk-artifact',
    result: 'passed',
    runUrl: args.runUrl ?? null,
    commit,
    unit: {
      package: identity.package,
      version: identity.version,
      moduleId: identity.moduleId,
      schemaVersion: identity.schemaVersion,
      runtimeKind: identity.runtimeKind,
      factoryName: identity.factoryName,
      contentPolicy: identity.contentPolicy,
      sourceHash: identity.source.sha256,
      buildHash: identity.artifact.sha256,
    },
    commands,
    manifest: MANIFEST_FILE,
    manifestSha256: sha256(manifestBytes),
    artifact: {path: ZIP_FILE, sha256: artifact.sha256, size: artifact.size},
    setHash,
    fileCount: files.length,
    generatedBy: TOOL,
  };
  writeFileSync(path.join(outDir, RECEIPT_FILE), `${JSON.stringify(receipt, null, 2)}\n`, 'utf8');

  const result = inspect({
    artifact: path.join(outDir, ZIP_FILE),
    manifest: path.join(outDir, MANIFEST_FILE),
    receipt: path.join(outDir, RECEIPT_FILE),
    root,
    distributionDir: args.distributionDir,
    whitelist,
  });
  result.notes.forEach(note => console.log(`note: ${note}`));
  if (result.problems.length) fail(result.problems, '出件自检失败');
  console.log(JSON.stringify({
    commit,
    artifact: {path: ZIP_FILE, sha256: artifact.sha256, size: artifact.size, fileCount: artifact.fileCount},
    setHash,
    files: files.map(file => ({path: file.path, source: file.source, size: file.size, sha256: file.sha256})),
    outDir,
    manifest: path.join(outDir, MANIFEST_FILE),
    receipt: path.join(outDir, RECEIPT_FILE),
    runUrl: receipt.runUrl,
  }, null, 2));
};

const verify = (args) => {
  for (const required of ['artifact', 'manifest', 'receipt']) {
    if (!args[required]) usage(`verify 需要 --${required}`);
  }
  const problems = [];
  const whitelist = loadWhitelist(problems);
  if (problems.length) fail(problems, '出件白名单非法');
  const result = inspect({
    artifact: path.resolve(args.artifact),
    manifest: path.resolve(args.manifest),
    receipt: path.resolve(args.receipt),
    root: args.root ? path.resolve(args.root) : null,
    expectHead: args.expectHead,
    distributionDir: args.distributionDir ? path.resolve(args.distributionDir) : null,
    whitelist,
  });
  result.notes.forEach(note => console.log(`note: ${note}`));
  if (result.problems.length) fail(result.problems);
  console.log(JSON.stringify({
    result: 'passed',
    commit: result.manifest.commit,
    artifact: result.manifest.artifact,
    setHash: result.manifest.setHash,
    files: result.manifest.files.map(file => ({path: file.path, size: file.size, sha256: file.sha256})),
  }, null, 2));
};

const inventory = (args) => {
  const problems = [];
  const whitelist = loadWhitelist(problems);
  if (problems.length) fail(problems, '出件白名单非法');
  const root = path.resolve(args.root ?? process.cwd());
  const rows = [];
  for (const member of [...whitelist.members].sort(byPath)) {
    const bytes = readFileSync(path.join(root, member.source));
    rows.push({path: member.path, source: member.source, role: member.role, size: bytes.length, sha256: sha256(bytes)});
  }
  console.log(JSON.stringify({
    distributionRoot: whitelist.distributionRoot,
    members: rows,
    setHash: canonicalSetHash(rows),
    consumerGenerated: whitelist.consumerGenerated,
  }, null, 2));
};

const main = () => {
  const args = parseArgs(process.argv.slice(2));
  if (args.command === 'assemble') assemble(args);
  else if (args.command === 'verify') verify(args);
  else if (args.command === 'inventory') inventory(args);
  else usage('缺少子命令');
};

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main();

export {canonicalSetHash, collectMembers, inspect, loadWhitelist, main};
